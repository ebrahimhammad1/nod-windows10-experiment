import { writeFileSync } from 'node:fs';
const [out] = process.argv.slice(2);
const list = await fetch('http://127.0.0.1:9222/json/list').then((r) => r.json());
const target = list.find((t) => t.type === 'page');
const ws = new WebSocket(target.webSocketDebuggerUrl);
let id = 0;
const pending = new Map();
const send = (m, p = {}) => new Promise((res, rej) => { const i = ++id; pending.set(i, { res, rej }); ws.send(JSON.stringify({ id: i, method: m, params: p })); });
ws.onmessage = (e) => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { const { res, rej } = pending.get(m.id); pending.delete(m.id); m.error ? rej(new Error(JSON.stringify(m.error))) : res(m.result); } };
await new Promise((r) => (ws.onopen = r));
await send('Runtime.enable');
const r1 = await send('Runtime.evaluate', { expression: `document.querySelector('.effort-picker-toggle')?.click(); 'toggle'` });
console.log(JSON.stringify(r1.result));
await new Promise((r) => setTimeout(r, 800));
const r2 = await send('Runtime.evaluate', { expression: `[...document.querySelectorAll('[role=menuitem],button,li')].find(b=>b.textContent.trim().startsWith('Auto'))?.click(); 'auto'` });
console.log(JSON.stringify(r2.result));
await new Promise((r) => setTimeout(r, 2500));
const shot = await send('Page.captureScreenshot', { format: 'png' });
writeFileSync(out, Buffer.from(shot.data, 'base64'));
console.log('saved', out);
process.exit(0);
